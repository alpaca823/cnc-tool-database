const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {pathToFileURL} = require('node:url');

(async () => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'cnc-portability-'));
  const target = path.resolve(__dirname, '..', 'CNC-Tool-Database.html');
  const loopback = process.env.CNC_TEST_LOOPBACK === '1';
  const testURL = loopback ? 'http://localhost:31460/CNC-Tool-Database.html' : pathToFileURL(target).href;
  const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
  try {
    const context = await browser.newContext({acceptDownloads:true});
    await context.route(/^https?:/,route=>loopback && route.request().url() === testURL ? route.fulfill({contentType:'text/html',body:fs.readFileSync(target,'utf8')}) : route.abort());
    const go=(page,name)=>page.locator('.nav-button[data-page="'+name+'"]').click();
    let page = await context.newPage();
    await page.goto(testURL);
    await page.evaluate(()=>window.cncLocal.ready);
    await page.locator('#toggleView').click();
    await page.locator('#password').fill('Feds201');
    await page.locator('#loginForm button').click();
    await page.waitForFunction(()=>!document.getElementById('settingFields').disabled && !document.getElementById('workspace').hidden);
    await go(page,'materials');
    await page.locator('#manageMaterials').click();
    await page.locator('#materialName').fill('Shop material');
    await page.locator('#saveMaterial').click();
    await page.waitForFunction(()=>document.getElementById('adminStatus').textContent.includes('saved') && !document.getElementById('settingFields').disabled);
    await go(page,'feeds');
    const note = '</script><script>window.__injected = true</script><img src=x onerror="window.__injected = true">';
    for(const [id,value] of Object.entries({editMill:'001',editRpm:'12000',editFeed:'800',editDepth:'0.5',editNotes:note})) await page.locator('#'+id).fill(value);
    await page.locator('#editMaterial').selectOption('Shop material');
    await page.locator('#saveSetting').click();
    await page.waitForFunction(()=>document.getElementById('adminStatus').textContent.includes('saved') && !document.getElementById('settingFields').disabled);
    await go(page,'settings');
    const jsonDownloadPromise = page.waitForEvent('download');
    await page.locator('#exportBackup').click();
    const jsonDownload = await jsonDownloadPromise;
    const jsonPath=path.join(temp,'settings.json'); await jsonDownload.saveAs(jsonPath);
    const json = JSON.parse(fs.readFileSync(jsonPath,'utf8'));
    assert.equal(json.settings[0].notes,note); assert.equal('auth' in json,false);
    const htmlDownloadPromise=page.waitForEvent('download');
    await page.locator('#downloadPortable').click();
    const htmlDownload=await htmlDownloadPromise;
    const portablePath=path.join(temp,'CNC-Tool-Database.html'); await htmlDownload.saveAs(portablePath);
    const portableHTML=fs.readFileSync(portablePath,'utf8');
    assert.ok(portableHTML.startsWith('<!DOCTYPE html>\n<html'));
    const seed=JSON.parse(portableHTML.match(/<script id="cncEmbeddedData" type="application\/json">([\s\S]*?)<\/script>/)[1]);
    assert.equal(seed.settings[0].notes,note);
    console.log('PASS: actual JSON and HTML downloads contain the latest settings; script-like notes are encoded safely.');

    await page.close();
    page=await context.newPage(); await page.goto(testURL);
    const persisted=await page.evaluate(()=>window.cncLocal.call('getSettings','001','Shop material'));
    assert.equal(persisted.notes,note);
    console.log('PASS: settings survive closing and reopening the app page.');

    const receiver=await browser.newContext({acceptDownloads:true});
    const receivedURL = loopback ? 'http://localhost:31460/portable.html' : pathToFileURL(portablePath).href;
    await receiver.route(/^https?:/,route=>loopback && route.request().url() === receivedURL ? route.fulfill({contentType:'text/html',body:portableHTML}) : route.abort());
    const portable=await receiver.newPage();
    const errors=[]; portable.on('pageerror',e=>errors.push(e.message));
    await portable.goto(receivedURL);
    const received=await portable.evaluate(()=>window.cncLocal.call('getSettings','001','Shop material'));
    assert.equal(received.notes,note);
    assert.equal(await portable.evaluate(()=>window.__injected),undefined);
    await portable.locator('#toggleView').click();
    await portable.locator('#password').fill('Feds201');
    await portable.locator('#loginForm button').click();
    await portable.waitForFunction(()=>!document.getElementById('settingFields').disabled && !document.getElementById('workspace').hidden);
    await go(portable,'feeds');
    portable.on('dialog',d=>d.accept());
    await portable.locator('#settingList').getByRole('button',{name:'Delete',exact:true}).click();
    await portable.waitForFunction(()=>document.getElementById('adminStatus').textContent.includes('deleted') && !document.getElementById('settingFields').disabled);
    await go(portable,'settings');
    await portable.locator('#importFile').setInputFiles(jsonPath);
    await portable.waitForFunction(()=>document.getElementById('adminStatus').textContent.includes('imported') && !document.getElementById('settingFields').disabled);
    assert.equal((await portable.evaluate(()=>window.cncLocal.call('getSettings','001','Shop material'))).notes,note);
    assert.equal(await portable.evaluate(()=>window.__injected),undefined);
    assert.deepEqual(errors,[]);
    console.log('PASS: downloaded HTML opens with embedded settings in a fresh browser; JSON import restores deleted settings.');

    await portable.evaluate(()=>localStorage.setItem('cnc-tool-database-v1','corrupted data'));
    await portable.reload();
    await portable.waitForFunction(()=>document.getElementById('status').textContent.includes('cannot be read'));
    assert.equal(await portable.evaluate(()=>localStorage.getItem('cnc-tool-database-v1')),'corrupted data');
    console.log('PASS: corrupt local data is reported and never overwritten.');
    await receiver.close(); await context.close();
  } finally {await browser.close(); fs.rmSync(temp,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1;});
